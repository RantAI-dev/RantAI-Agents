/**
 * IKAT-Bench step 6 — render a run's summary JSON into the manuscript's tables.
 *
 * This exists so no number is ever hand-copied into the paper. Hand-copying is
 * how a transposed digit becomes a published claim, and it is also how "just
 * round this one up" happens. The tables below are a pure function of
 * `summary-<run>.json`; if a cell looks wrong, the fix is in the run, not here.
 *
 * Missing values print as "n/a" rather than 0 or a blank: a metric that had no
 * scoreable evidence is absent data, and must not read as a measured zero.
 *
 * Usage:
 *   bun tests/bench-kb/src/ikat/render-results.ts <run-name>
 */
import * as fs from "node:fs"
import * as path from "node:path"

const BENCH_ROOT = path.resolve(import.meta.dirname, "../..")
const RESULTS_DIR = path.join(BENCH_ROOT, "corpus", "results")

interface SystemRow {
  system: string
  n: number
  scoredQuestions?: number
  groundedFigureF1: number | null
  figureSelectionF1: number | null
  placementAccuracyAt1: number | null
  meanAbsDisplacement: number | null
  answerCompleteness: number | null
  answerFaithfulness: number | null
  answerHelpfulness: number | null
  meanLatencyMs: number | null
  meanGenTokens: number | null
  figureDependent: { n: number; groundedFigureF1: number | null }
}

interface Summary {
  run: string
  generatedAt: string
  config: Record<string, unknown>
  corpus: { docs: number; questions: number }
  systems: SystemRow[]
  placementValidity: {
    n: number
    pearson: number | null
    exactAgreement: number | null
    within1: number | null
  }
}

/** Fixed-precision, or an explicit "n/a" — never a silent zero. */
const f = (v: number | null | undefined, d = 3): string =>
  v === null || v === undefined || !Number.isFinite(v) ? "n/a" : v.toFixed(d)

/** Human-facing system names, matching the manuscript's S-numbering. */
const LABEL: Record<string, string> = {
  text_only: "S0 text-only",
  caption_match: "S1 caption-match (production)",
  co_embed: "S2 co-embedding",
  anchor: "S4 anchor (ours)",
  anchor_vlm: "S5 anchor + VLM description",
  anchor_hybrid: "S6 anchor + description retrieval (hybrid)",
  mramg_match: "S7 MRAMG bipartite matching (published)",
  vinqa_cite: "S8 VinQA citation-order (published)",
  anchor_mramg_place: "A1 anchor selection + MRAMG placement",
  anchor_vinqa_place: "A2 anchor selection + VinQA placement",
  anchor_end: "A3 anchor selection + no placement rule",
  sel_wide: "B1 wide pool, no ranking",
  sel_ranked: "B2 wide pool + description ranking",
  sel_gated: "B3 wide + ranking + admission floor",
  sel_llm: "B4 wide + model-picked selection",
  sel_rerank: "B5 cross-encoder reranked selection",
}

function main() {
  const run = process.argv[2]
  if (!run) {
    console.error("usage: render-results.ts <run-name>")
    process.exit(1)
  }
  const p = path.join(RESULTS_DIR, `summary-${run}.json`)
  if (!fs.existsSync(p)) {
    console.error(`no such summary: ${p}`)
    process.exit(1)
  }
  const s = JSON.parse(fs.readFileSync(p, "utf-8")) as Summary

  const out: string[] = []
  out.push(`<!-- generated by render-results.ts from summary-${run}.json — do not edit by hand -->`)
  out.push("")
  out.push(
    `Run \`${s.run}\` · ${s.corpus.questions} questions over ${s.corpus.docs} books · ` +
      `generator \`${s.config.generator}\` · embedder \`${s.config.embedder}\` · ` +
      `provider \`${s.config.provider ?? "n/a"}\` · top-k ${s.config.topK}`,
  )
  out.push("")

  // ── Main table ──
  out.push("| System | GF-F1 | Selection F1 | PA@1 | mean \\|PD\\| | fig-dep GF-F1 | latency (ms) |")
  out.push("|---|---|---|---|---|---|---|")
  for (const r of s.systems) {
    out.push(
      `| ${LABEL[r.system] ?? r.system} | **${f(r.groundedFigureF1)}** | ${f(r.figureSelectionF1)} | ` +
        `${f(r.placementAccuracyAt1)} | ${f(r.meanAbsDisplacement, 2)} | ${f(r.figureDependent.groundedFigureF1)} | ` +
        `${f(r.meanLatencyMs, 0)} |`,
    )
  }
  out.push("")

  // ── C2: does selection quality predict placement quality? ──
  // The point of the paper hangs on these two columns diverging.
  out.push("**C2 — selection vs placement.** If placement were implied by retrieval, these would track each other.")
  out.push("")
  out.push("| System | Selection F1 | PA@1 | gap (sel − PA@1) |")
  out.push("|---|---|---|---|")
  for (const r of s.systems) {
    const gap =
      r.figureSelectionF1 !== null && r.placementAccuracyAt1 !== null
        ? f(r.figureSelectionF1 - r.placementAccuracyAt1)
        : "n/a"
    out.push(`| ${LABEL[r.system] ?? r.system} | ${f(r.figureSelectionF1)} | ${f(r.placementAccuracyAt1)} | ${gap} |`)
  }
  out.push("")

  // ── Judged measures, only when a judge actually ran ──
  const judged = s.systems.some((r) => r.answerCompleteness !== null)
  if (judged) {
    out.push("| System | Completeness | Faithfulness | Helpfulness |")
    out.push("|---|---|---|---|")
    for (const r of s.systems) {
      out.push(
        `| ${LABEL[r.system] ?? r.system} | ${f(r.answerCompleteness, 2)} | ${f(r.answerFaithfulness, 2)} | ` +
          `${f(r.answerHelpfulness, 2)} |`,
      )
    }
  } else {
    out.push("*Answer-quality columns omitted: this run used `--judge 0`, so no judged measure exists.*")
  }
  out.push("")

  // ── Metric validity ──
  const v = s.placementValidity
  out.push(
    v.n > 0
      ? `**Metric validity** (n=${v.n}): Pearson r=${f(v.pearson)}, exact agreement ${f(v.exactAgreement)}, ` +
          `within-1 ${f(v.within1)}.`
      : "**Metric validity**: not run (judge disabled). §5.5 remains PENDING.",
  )

  const dest = path.join(RESULTS_DIR, `tables-${run}.md`)
  fs.writeFileSync(dest, out.join("\n") + "\n")
  console.log(out.join("\n"))
  console.log(`\n[ikat] wrote ${dest}`)
}

if (import.meta.main) main()
